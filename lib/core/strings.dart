import 'package:flutter/foundation.dart';

/// Tiny translation layer: English text is the key, Urdu is the value.
class Lang {
  static final ValueNotifier<String> code = ValueNotifier<String>('en');
  static bool get isUrdu => code.value == 'ur';
}

String tr(String s) => Lang.isUrdu ? (_ur[s] ?? s) : s;

/// Translates a template such as '{n} songs' and fills in the placeholders.
String tn(String template, Map<String, Object> vars) {
  var out = tr(template);
  vars.forEach((k, v) {
    out = out.replaceAll('{$k}', '$v');
  });
  return out;
}

